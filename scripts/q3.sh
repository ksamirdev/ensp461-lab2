rec "docker exec s-vol sh -c 'echo samir-volume-note > /data/note.txt'"
rec "docker rm -f s-vol"
rec "docker run --rm -v lab2-notes:/data $U cat /data/note.txt"
rec "docker volume inspect lab2-notes --format '{{.Name}} {{.Driver}} {{.Mountpoint}}'"
rec "docker volume rm lab2-notes"
rec "echo from-host > '$HOSTDIR/shared.txt'"
rec "docker run --rm -v '$HOSTDIR':/data $U cat /data/shared.txt"
rec "docker run --rm -v '$HOSTDIR':/data $U sh -c 'echo from-container >> /data/shared.txt'"
rec "cat '$HOSTDIR/shared.txt'"
